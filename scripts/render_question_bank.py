#!/usr/bin/env python3
"""Render the question bank overview document from question_bank/*.yaml."""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

import yaml

_ROLE_LABELS: dict[str, str] = {
    "core_positive": "core positive",
    "boundary_negative": "boundary negative",
    "coverage": "coverage",
    "freshness_precision": "freshness/precision",
    "shape_completeness": "shape/no-data",
    "agent_contract": "agent contract",
}


def _load(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def render(root: Path) -> str:
    questions = _load(root / "questions.yaml")["questions"]
    capabilities = _load(root / "capabilities.yaml")["capabilities"]
    sources = {
        str(entry["source_id"]): str(entry["name"])
        for entry in _load(root / "sources.yaml")["sources"]
    }

    lines = [
        "# CAP Question Bank Overview",
        "",
        f"**{len(capabilities)} capabilities, {len(questions)} questions.** "
        "Generated by "
        "`scripts/render_question_bank.py`; do not edit by hand.",
        "",
        "## Capability × role matrix",
        "",
        "| Capability | core | boundary | coverage | freshness/precision | "
        "shape/no-data | agent contract |",
        "|---|---|---|---|---|---|---|",
    ]
    role_order = [
        "core_positive",
        "boundary_negative",
        "coverage",
        "freshness_precision",
        "shape_completeness",
        "agent_contract",
    ]
    roles_by_cap: dict[str, set[str]] = {
        str(cap["cap_id"]): set() for cap in capabilities
    }
    for question in questions:
        roles_by_cap.setdefault(str(question["cap_id"]), set()).add(
            str(question["role"])
        )
    for cap in capabilities:
        cap_id = str(cap["cap_id"])
        cells = [
            "✅" if role in roles_by_cap.get(cap_id, set()) else "—"
            for role in role_order
        ]
        lines.append(f"| `{cap_id}` | {' | '.join(cells)} |")

    lines += ["", "## Questions by capability", ""]
    for cap in capabilities:
        cap_id = str(cap["cap_id"])
        cap_questions = sorted(
            (q for q in questions if str(q["cap_id"]) == cap_id),
            key=lambda q: (str(q["role"]), str(q["question_id"])),
        )
        if not cap_questions:
            continue
        lines.append(f"### {cap['name']} (`{cap_id}`)")
        lines.append("")
        lines.append("| Question | Role | Scenario | Task | Referee |")
        lines.append("|---|---|---|---|---|")
        for question in cap_questions:
            referee = ", ".join(
                sources.get(str(source_id), str(source_id))
                for source_id in question.get("evaluation_contract", {}).get(
                    "reference_source_ids", question.get("source_ids", [])
                )
            )
            attached = (
                "+".join(
                    sorted(
                        str(reference["version"])
                        for reference in question.get("scenario_refs", [])
                    )
                )
                or "—"
            )
            lines.append(
                f"| `{question['question_id']}` | "
                f"{_ROLE_LABELS.get(str(question['role']), question['role'])} | "
                f"{attached} | "
                f"{question['task']} | {referee} |"
            )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bank-root", type=Path, default=Path("question_bank"))
    parser.add_argument(
        "--output", type=Path, default=Path("docs/question-bank-overview.md")
    )
    args = parser.parse_args()
    args.output.write_text(render(args.bank_root), encoding="utf-8")


if __name__ == "__main__":
    main()
